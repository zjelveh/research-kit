@pytest.mark.parametrize("old", ["OLD\n", None])
def test_second_rename_failure_restores_numbers_tex(tmp_path, capsys, monkeypatch, old):
    p = project(tmp_path, r=r_script(R_ENTRY.format(n="coverageMain")))
    out = p / "paper" / "generated" / "numbers.tex"
    if old:
        write(out, old)
    real, calls = numbers_build.Path.replace, [0]

    def flaky(self, target):
        calls[0] += 1
        if calls[0] == 2:
            raise OSError("boom")
        return real(self, target)

    monkeypatch.setattr(numbers_build.Path, "replace", flaky)
    assert numbers_build.main(["--project", str(p)]) == 2
    assert "numbers.tex was restored" in capsys.readouterr().err
    assert (out.read_text() == old) if old else not out.exists()
    assert not list((p / "paper" / "generated").glob("*.tmp")) and not list((p / "state").glob("*.tmp"))


