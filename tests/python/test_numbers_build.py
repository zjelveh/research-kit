EMIT = PLUGIN_ROOT / "scripts"
LEDGER = "# Claims ledger\n\n<!-- BEGIN GENERATED -->\n<!-- END GENERATED -->\n\n## Other claims\n"
R_ENTRY = 'list(name = "{n}", value = 0.9412, format = "%.2f", src = "analysis/summary.csv")'
PY_ENTRY = 'dict(name="{n}", value=0.9412, format="%.2f", src="analysis/summary.csv")'


def r_script(*entries: str) -> str:
    return f'source("{EMIT}/numbers_emit.R")\nemit_numbers(list({", ".join(entries)}))\n'


def py_script(*entries: str) -> str:
    return ("import importlib.util\n"
            f"s = importlib.util.spec_from_file_location('numbers_emit', '{EMIT}/numbers_emit.py')\n"
            "m = importlib.util.module_from_spec(s)\ns.loader.exec_module(m)\n"
            f"m.emit_numbers([{', '.join(entries)}])\n")


def project(tmp_path, languages="[r]", r=None, py=None, commit=True):
    p = minimal_project(tmp_path, CONFIG.replace("languages: [r]", f"languages: {languages}"))
    write(p / "state" / "CLAIMS_LEDGER.md", LEDGER)
    (p / "paper" / "generated").mkdir(parents=True)
    write(p / "analysis" / "summary.csv", "x\n0.94\n")
    if r is not None:
        write(p / "analysis" / "numbers" / "make_numbers.R", r)
    if py is not None:
        write(p / "analysis" / "numbers" / "make_numbers.py", py)
    stubs = {"r": {".Rprofile": "# test stub\n", "renv.lock": "{}\n"},
             "python": {"pyproject.toml": '[project]\nname = "t"\nversion = "0"\n', "uv.lock": "version = 1\n"}}
    for lang in re.findall(r"\w+", languages):
        for name, text in stubs[lang].items():
            write(p / name, text)
    if commit:
        init_repo(p)
    return p


