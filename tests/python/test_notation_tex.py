from build_fixture import minimal_project, write
from notation_tex import main

HEAD = "# Notation\n\n| Symbol | Meaning | Macro | Introduced |\n|---|---|---|---|\n"


def proj(tmp_path, rows):
    p = minimal_project(tmp_path)
    write(p / "notes" / "notation.md", HEAD + rows)
    (p / "paper" / "generated").mkdir(parents=True)
    return p


def test_generates_macros(tmp_path):
    p = proj(tmp_path, "| `\\tau_s` | effect under spec s | `\\tauS` | §2 |\n")
    assert main(["--project", str(p)]) == 0
    out = (p / "paper" / "generated" / "notation.tex").read_text()
    assert "\\newcommand{\\tauS}{\\ensuremath{\\tau_s}}" in out
    assert out.startswith("% Generated by research-kit notation_tex.py")


def test_empty_table_ok(tmp_path):
    assert main(["--project", str(proj(tmp_path, ""))]) == 0


def test_duplicate_macro_fails(tmp_path):
    rows = "| `a` | x | `\\foo` | §1 |\n| `b` | y | `\\foo` | §1 |\n"
    assert main(["--project", str(proj(tmp_path, rows))]) == 2


def test_bad_macro_name_fails(tmp_path):
    assert main(["--project", str(proj(tmp_path, "| `a` | x | `\\foo2` | §1 |\n"))]) == 2


def test_missing_backticks_fails(tmp_path):
    assert main(["--project", str(proj(tmp_path, "| a | x | `\\foo` | §1 |\n"))]) == 2


def test_missing_table_fails(tmp_path):
    p = proj(tmp_path, "")
    (p / "notes" / "notation.md").write_text("# Notation\n")
    assert main(["--project", str(p)]) == 2
