#!/usr/bin/env python3
"""Generate notation.tex from the table in notes/notation.md (spec §5.2). Exit: 0 ok, 2 error."""
from __future__ import annotations

import argparse
import datetime as dt
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from kitlib import KitError, atomic_write, load_config  # noqa: E402

HEADER = ["symbol", "meaning", "macro", "introduced"]
TICK_RE = re.compile(r"^`(.+)`$")
MACRO_RE = re.compile(r"^\\[A-Za-z]+$")


def cells(line: str) -> list[str]:
    return [c.strip() for c in line.strip().strip("|").split("|")]


def parse(md: Path) -> list[tuple[str, str]]:
    lines = md.read_text(encoding="utf-8").splitlines()
    for k, line in enumerate(lines):
        if line.startswith("|") and [c.lower() for c in cells(line)] == HEADER:
            break
    else:
        raise KitError(f"{md}: no table with header | Symbol | Meaning | Macro | Introduced |")
    rows, seen = [], set()
    for lineno, line in enumerate(lines[k + 2:], start=k + 3):
        if not line.startswith("|"):
            break
        c = cells(line)
        if len(c) != 4:
            raise KitError(f"{md}:{lineno}: expected 4 cells, got {len(c)}")
        sym, mac = TICK_RE.match(c[0]), TICK_RE.match(c[2])
        if not sym or not mac:
            raise KitError(f"{md}:{lineno}: Symbol and Macro cells must be in backticks")
        macro = mac.group(1)
        if not MACRO_RE.match(macro):
            raise KitError(f"{md}:{lineno}: macro {macro!r} must be a backslash plus letters only")
        if macro in seen:
            raise KitError(f"{md}:{lineno}: duplicate macro {macro}")
        seen.add(macro)
        rows.append((macro, sym.group(1)))
    return rows


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--project", type=Path, default=Path.cwd())
    a = ap.parse_args(argv)
    try:
        cfg = load_config(a.project)
        md = a.project / "notes" / "notation.md"
        if not md.is_file():
            raise KitError(f"{md}: file not found")
        rows = parse(md)
        out = a.project / cfg["notation_tex"]
        if not out.parent.is_dir():
            raise KitError(f"{out.parent} does not exist (is the paper attached?)")
        text = [f"% Generated by research-kit notation_tex.py from notes/notation.md on "
                f"{dt.date.today().isoformat()}. Do not edit."]
        text += [f"\\newcommand{{{m}}}{{\\ensuremath{{{s}}}}}" for m, s in rows]
        atomic_write(out, "\n".join(text) + "\n")
    except KitError as e:
        print(f"notation_tex: ERROR: {e}", file=sys.stderr)
        return 2
    print(f"notation.tex: {len(rows)} macros")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
